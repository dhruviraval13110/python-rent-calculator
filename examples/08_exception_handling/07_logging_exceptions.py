def predict(value):

    logging.info(
        "Prediction request received."
    )

    try:

        number = float(value)

        prediction = number * 2

        logging.info(
            "Prediction completed successfully."
        )

        return prediction

    except ValueError:

        logging.exception(
            "Prediction failed because input "
            "was invalid."
        )

        return None


print(
    "Prediction:",
    predict("10.5")
)

print(
    "Prediction:",
    predict("AI")
)

