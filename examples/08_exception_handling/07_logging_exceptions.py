print("\nExample 12 - Dataset Logging")


def load_dataset(dataset):

    logging.info(
        "Dataset loading started."
    )

    try:

        if dataset is None:

            raise ValueError(
                "Dataset cannot be None."
            )

        if len(dataset) == 0:

            raise ValueError(
                "Dataset is empty."
            )

        logging.info(
            "Dataset loaded successfully. Rows: %d",
            len(dataset)
        )

    except ValueError:

        logging.exception(
            "Dataset loading failed."
        )


load_dataset(
    [10, 20, 30, 40]
)

load_dataset([])

